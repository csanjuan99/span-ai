func TestHostMergeReturnsErrConflictForAConflictRefusal(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("the fake gh is a shell script")
	}
	bin := t.TempDir()
	script := "#!/bin/sh\necho \"$GH_STDERR\" >&2\nexit 1\n"
	if err := os.WriteFile(filepath.Join(bin, "gh"), []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))
	host := Host{Workspace: t.TempDir(), State: t.TempDir()}
	t.Setenv("GH_STDERR", "X Pull request #3 is not mergeable: the merge commit cannot be cleanly created.")
	err := host.Merge(context.Background(), "https://example.test/pull/3")
	if !errors.Is(err, ErrConflict) || !errors.Is(err, engine.ErrConflict) {
		t.Fatalf("err = %v", err)
	}
	t.Setenv("GH_STDERR", "HTTP 502: Bad Gateway")
	err = host.Merge(context.Background(), "https://example.test/pull/3")
	if err == nil || errors.Is(err, ErrConflict) {
		t.Fatalf("err = %v", err)
	}
}

