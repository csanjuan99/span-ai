// diverged builds dev with base, branches feat/x from it, applies ours there and theirs on
// dev, and leaves feat/x checked out. Each step is a commit.
func diverged(t *testing.T, base, ours, theirs func(dir string)) string {
	t.Helper()
	dir := repo(t)
	git(t, dir, "checkout", "-q", "-b", "dev")
	write(t, dir, "README.md", "readme\n")
	if base != nil {
		base(dir)
	}
	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-q", "-m", "base")
	git(t, dir, "checkout", "-q", "-b", "feat/x")
	if ours != nil {
		ours(dir)
		git(t, dir, "add", "-A")
		git(t, dir, "commit", "-q", "--allow-empty", "-m", "ours")
	}
	git(t, dir, "checkout", "-q", "dev")
	if theirs != nil {
		theirs(dir)
		git(t, dir, "add", "-A")
		git(t, dir, "commit", "-q", "--allow-empty", "-m", "theirs")
	}
	git(t, dir, "checkout", "-q", "feat/x")
	return dir
}

func integrate(t *testing.T, dir string) engine.Integration {
	t.Helper()
	got, err := Git{Dir: dir}.Integrate(context.Background(), "dev")
	if err != nil {
		t.Fatal(err)
	}
	return got
}

func onlyFile(t *testing.T, got engine.Integration, path, kind string) engine.ConflictFile {
	t.Helper()
	for _, file := range got.Files {
		if file.Path == path {
			if file.Kind != kind {
				t.Fatalf("%s kind = %s, want %s (%+v)", path, file.Kind, kind, got.Files)
			}
			return file
		}
	}
	t.Fatalf("%s not conflicted: %+v", path, got.Files)
	return engine.ConflictFile{}
}

func TestIntegrateReportsAContentConflictWithItsSides(t *testing.T) {
	dir := diverged(t,
		func(d string) { write(t, d, "app.go", "package app\n\nconst Name = \"base\"\n") },
		func(d string) { write(t, d, "app.go", "package app\n\nconst Name = \"ours\"\n") },
		func(d string) { write(t, d, "app.go", "package app\n\nconst Name = \"theirs\"\n") },
	)
	got := integrate(t, dir)
	if got.Clean || len(got.Files) != 1 || got.Base != "dev" || got.BaseSHA == "" {
		t.Fatalf("%+v", got)
	}
	file := onlyFile(t, got, "app.go", "content")
	if !strings.Contains(file.Ours.Text, "ours") || !strings.Contains(file.Theirs.Text, "theirs") || !strings.Contains(file.Base.Text, "base") {
		t.Fatalf("sides %+v", file)
	}
	if merging, err := (Git{Dir: dir}).Merging(context.Background()); err != nil || !merging {
		t.Fatalf("merging = %v %v", merging, err)
	}
}

func TestIntegrateClassifiesEveryKindOfConflict(t *testing.T) {
	cases := []struct {
		name               string
		base, ours, theirs func(string)
		path, kind         string
	}{
		{"add-add", nil,
			func(d string) { write(t, d, "new.txt", "ours\n") },
			func(d string) { write(t, d, "new.txt", "theirs\n") }, "new.txt", "add-add"},
		{"modify-delete", func(d string) { write(t, d, "gone.txt", "base\n") },
			func(d string) { write(t, d, "gone.txt", "ours changed it\n") },
			func(d string) { must(t, os.Remove(filepath.Join(d, "gone.txt"))) }, "gone.txt", "modify-delete"},
		{"rename-delete", func(d string) { write(t, d, "old.txt", "one\ntwo\nthree\n") },
			func(d string) { git(t, d, "mv", "old.txt", "renamed.txt") },
			func(d string) { must(t, os.Remove(filepath.Join(d, "old.txt"))) }, "renamed.txt", "rename"},
		{"rename-rename", func(d string) { write(t, d, "old.txt", "one\ntwo\nthree\n") },
			func(d string) { git(t, d, "mv", "old.txt", "a.txt") },
			func(d string) { git(t, d, "mv", "old.txt", "b.txt") }, "b.txt", "rename"},
		{"binary", func(d string) { write(t, d, "logo.png", "\x00\x01base") },
			func(d string) { write(t, d, "logo.png", "\x00\x02ours") },
			func(d string) { write(t, d, "logo.png", "\x00\x03theirs") }, "logo.png", "binary"},
		{"lockfile", func(d string) { write(t, d, "web/package-lock.json", "{\"v\":1}\n") },
			func(d string) { write(t, d, "web/package-lock.json", "{\"v\":2}\n") },
			func(d string) { write(t, d, "web/package-lock.json", "{\"v\":3}\n") }, "web/package-lock.json", "lockfile"},
		{"generated header", func(d string) {
			write(t, d, "api.go", "// Code generated by tool. DO NOT EDIT.\npackage api\nvar A = 1\n")
		},
			func(d string) {
				write(t, d, "api.go", "// Code generated by tool. DO NOT EDIT.\npackage api\nvar A = 2\n")
			},
			func(d string) {
				write(t, d, "api.go", "// Code generated by tool. DO NOT EDIT.\npackage api\nvar A = 3\n")
			}, "api.go", "generated"},
		{"mode", nil,
			func(d string) {
				write(t, d, "tool.sh", "same\n")
				must(t, os.Chmod(filepath.Join(d, "tool.sh"), 0o755))
			},
			func(d string) { write(t, d, "tool.sh", "same\n") }, "tool.sh", "mode"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if tc.kind == "mode" && runtime.GOOS == "windows" {
				t.Skip("no executable bit to set")
			}
			dir := diverged(t, tc.base, tc.ours, tc.theirs)
			got := integrate(t, dir)
			if got.Clean {
				t.Fatalf("clean: %+v", got)
			}
			file := onlyFile(t, got, tc.path, tc.kind)
			if tc.kind == "binary" && (!file.Ours.Binary || file.Ours.Text != "") {
				t.Fatalf("binary side carries text: %+v", file.Ours)
			}
		})
	}
}

func TestIntegrateIsCleanWhenNothingConflicts(t *testing.T) {
	dir := diverged(t,
		func(d string) { write(t, d, "a.txt", "a\n") },
		func(d string) { write(t, d, "ours.txt", "ours\n") },
		func(d string) { write(t, d, "theirs.txt", "theirs\n") },
	)
	g := Git{Dir: dir}
	got := integrate(t, dir)
	if !got.Clean || !got.Merged || len(got.Files) != 0 {
		t.Fatalf("%+v", got)
	}
	before := git(t, dir, "rev-parse", "HEAD")
	sha, err := g.FinishMerge(context.Background(), "merge dev into feat/x")
	if err != nil {
		t.Fatal(err)
	}
	if sha == before || git(t, dir, "rev-parse", "HEAD^2") != git(t, dir, "rev-parse", "dev") {
		t.Fatalf("not a merge commit of dev: %s", sha)
	}
	if _, err := os.Stat(filepath.Join(dir, "theirs.txt")); err != nil {
		t.Fatal(err)
	}
}

