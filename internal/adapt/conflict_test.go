func TestResolveWritesEachSideAndFinishesTheMerge(t *testing.T) {
	dir := diverged(t,
		func(d string) {
			write(t, d, "a.txt", "base\n")
			write(t, d, "b.txt", "base\n")
			write(t, d, "c.txt", "base\n")
		},
		func(d string) {
			write(t, d, "a.txt", "ours\n")
			write(t, d, "b.txt", "ours\n")
			write(t, d, "c.txt", "ours\n")
		},
		func(d string) {
			write(t, d, "a.txt", "theirs\n")
			write(t, d, "b.txt", "theirs\n")
			must(t, os.Remove(filepath.Join(d, "c.txt")))
		},
	)
	got := integrate(t, dir)
	g := Git{Dir: dir}
	a := onlyFile(t, got, "a.txt", "content")
	b := onlyFile(t, got, "b.txt", "content")
	ctx := context.Background()
	preview, err := g.Preview(ctx, "b.txt", b.Ours, engine.FileResolution{Blob: b.Theirs.SHA, Mode: b.Theirs.Mode})
	if err != nil || !strings.Contains(preview, "-ours") || !strings.Contains(preview, "+theirs") || !strings.HasPrefix(preview, "--- a/b.txt\n+++ b/b.txt\n") {
		t.Fatalf("preview %q %v", preview, err)
	}
	err = g.Resolve(ctx, map[string]engine.FileResolution{
		"a.txt": {Blob: a.Ours.SHA, Mode: a.Ours.Mode},
		"b.txt": {Write: true, Content: []byte("ours and theirs\n")},
		"c.txt": {Delete: true},
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := g.FinishMerge(ctx, "merge dev into feat/x: resolve conflicts"); err != nil {
		t.Fatal(err)
	}
	if body := git(t, dir, "show", "HEAD:a.txt"); body != "ours" {
		t.Fatalf("a.txt = %q", body)
	}
	if body := git(t, dir, "show", "HEAD:b.txt"); body != "ours and theirs" {
		t.Fatalf("b.txt = %q", body)
	}
	if _, err := os.Stat(filepath.Join(dir, "c.txt")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("c.txt still there: %v", err)
	}
	if status := git(t, dir, "status", "--porcelain"); status != "" {
		t.Fatalf("tree not clean: %q", status)
	}
}

func TestResolveRefusesMarkersAndPathsOutsideTheCheckout(t *testing.T) {
	dir := diverged(t,
		func(d string) { write(t, d, "a.txt", "base\n") },
		func(d string) { write(t, d, "a.txt", "ours\n") },
		func(d string) { write(t, d, "a.txt", "theirs\n") },
	)
	integrate(t, dir)
	g := Git{Dir: dir}
	ctx := context.Background()
	err := g.Resolve(ctx, map[string]engine.FileResolution{"a.txt": {Write: true, Content: []byte("<<<<<<< HEAD\nours\n=======\ntheirs\n>>>>>>> dev\n")}})
	if err == nil || !strings.Contains(err.Error(), "markers") {
		t.Fatalf("markers accepted: %v", err)
	}
	// The worktree file still has git's markers; staging it as is must fail too.
	if err := g.Resolve(ctx, map[string]engine.FileResolution{"a.txt": {Stage: true}}); err == nil {
		t.Fatal("a file with markers was staged")
	}
	outside := filepath.Join(t.TempDir(), "evil.txt")
	for _, path := range []string{"../evil.txt", "sub/../../evil.txt", outside, ".git/config", ""} {
		if err := g.Resolve(ctx, map[string]engine.FileResolution{path: {Write: true, Content: []byte("x")}}); err == nil {
			t.Fatalf("path %q accepted", path)
		}
	}
	if _, err := os.Stat(outside); !errors.Is(err, os.ErrNotExist) {
		t.Fatal("a file was written outside the checkout")
	}
	if left := git(t, dir, "ls-files", "-u"); left == "" {
		t.Fatal("a refused resolution staged something")
	}
	if _, err := g.FinishMerge(ctx, "merge"); err == nil {
		t.Fatal("finished a merge with unmerged paths")
	}
}

