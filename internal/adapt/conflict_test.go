// The whole phase against real git: the run holds on the conflict, the choice is merged,
// committed and pushed, prove runs on the merge commit, and the merge goes through.
func TestTheMergeStageResolvesARealConflict(t *testing.T) {
	origin := diverged(t,
		func(d string) { write(t, d, "a.txt", "base\n") },
		func(d string) { write(t, d, "a.txt", "ours\n") },
		func(d string) { write(t, d, "a.txt", "theirs\n") },
	)
	git(t, origin, "config", "receive.denyCurrentBranch", "ignore")
	clone := t.TempDir()
	git(t, clone, "clone", "-q", "-b", "feat/x", origin, ".")
	git(t, clone, "config", "user.email", "span@example.test")
	git(t, clone, "config", "user.name", "Span")
	head := git(t, clone, "rev-parse", "HEAD")
	root := t.TempDir()
	id := "span-e"
	url := "local:" + id + ":feat/x"
	write(t, root, filepath.Join(id, "change.url"), url+"\n")
	write(t, root, filepath.Join(id, "brief.md"), "Keep a.txt.\n")
	off := false
	cur := engine.Cursor{ID: id, Iteration: 1, Stage: "merge", GitSHA: head, ChangeURL: url, Branch: "feat/x", Base: "dev", Workspace: clone}
	raw, err := json.Marshal(cur)
	if err != nil {
		t.Fatal(err)
	}
	write(t, root, filepath.Join(id, "cursor.json"), string(raw))
	opt := engine.Options{
		Workspace: clone, Root: root, Brief: "Keep a.txt.",
		Policy: policy.File{Feature: "payments", Prove: policy.Bands{Fast: []string{"git --version"}, Baseline: &off}},
		Agents: quietAgents{}, Check: Exec{}, Source: Git{Dir: clone},
		Review: LocalReview{Dir: root}, Release: CommandRelease{},
	}
	ctx := context.Background()
	got, err := engine.Resume(ctx, opt, id)
	if err != nil {
		t.Fatal(err)
	}
	if got.Reason != engine.ConflictChooseReason {
		t.Fatalf("%+v", got)
	}
	snap, err := engine.Load(root, id)
	if err != nil {
		t.Fatal(err)
	}
	group := snap.Cursor.Conflict.Groups[0]
	if group.Kind != "content" || group.Options[1].ID != "theirs" || !strings.Contains(group.Options[1].Diff, "+theirs") {
		t.Fatalf("group %+v", group)
	}
	if git(t, clone, "rev-parse", "HEAD") != head {
		t.Fatal("the branch moved before a choice")
	}
	if err := engine.ChooseConflict(root, id, map[string]string{group.ID: "theirs"}); err != nil {
		t.Fatal(err)
	}
	got, err = engine.Resume(ctx, opt, id)
	if err != nil {
		t.Fatal(err)
	}
	if got.Verdict != "advance" {
		t.Fatalf("%+v", got)
	}
	merged := git(t, clone, "rev-parse", "HEAD")
	if git(t, clone, "show", "HEAD:a.txt") != "theirs" || git(t, clone, "rev-parse", "HEAD^2") != git(t, origin, "rev-parse", "dev") {
		t.Fatal("the merge commit is not the chosen resolution of dev")
	}
	if git(t, origin, "rev-parse", "feat/x") != merged {
		t.Fatal("the merge commit was not pushed")
	}
	prove, err := os.ReadFile(filepath.Join(root, id, "iter", "2", "prove.json"))
	if err != nil || !strings.Contains(string(prove), merged) {
		t.Fatalf("prove did not run on the merge commit: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, id, "merged")); err != nil {
		t.Fatal("the change was not merged after prove")
	}
}
